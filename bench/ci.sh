#!/usr/bin/env bash
# Benchmark run used by CI (.github/workflows/bench.yml). Also works locally.
#
# Clones ripgrep at a pinned commit, runs bench/worktrees.sh, then rewrites
# bench/RESULTS.md and appends to bench/history.tsv.
#
# Env:
#   BENCH_DIR      where to work (put it on the filesystem to measure)
#   BENCH_FS_NOTE  free-text filesystem description for the results
set -euo pipefail

HERE=$(cd "$(dirname "$0")" && pwd)
ROOT=$(cd "$HERE/.." && pwd)
RG_URL=https://github.com/BurntSushi/ripgrep
# Pinned so changes between runs come from cargo-slot, not ripgrep.
RG_REV=178cc027e283fd965cb72d0a7395b219eada170c
EDIT=crates/searcher/src/lib.rs
N=5
ROUNDS=4

export BENCH_DIR=${BENCH_DIR:-$(mktemp -d)}
mkdir -p "$BENCH_DIR"
RG=$BENCH_DIR/ripgrep
if [ ! -d "$RG" ]; then
  git clone -q --filter=blob:none "$RG_URL" "$RG"
fi
git -C "$RG" checkout -q --detach "$RG_REV"
(cd "$RG" && cargo fetch -q)

(cd "$ROOT" && cargo build -q --release --locked)

TSV=$(mktemp)
BENCH_TSV=$TSV "$HERE/worktrees.sh" "$RG" "$N" "$ROUNDS" "$EDIT"

# Context for the results.
date=$(date -u +%Y-%m-%d)
rev=$(git -C "$ROOT" rev-parse --short HEAD)
os=$(uname -sm)
if [ "$(uname -s)" = Darwin ]; then
  cpu=$(sysctl -n machdep.cpu.brand_string)
  cores=$(sysctl -n hw.ncpu)
else
  cpu=$(awk -F': ' '/model name/{print $2; exit}' /proc/cpuinfo)
  cpu=${cpu:-$(uname -m)}
  cores=$(nproc)
fi
fs=${BENCH_FS_NOTE:-$(df -PT "$BENCH_DIR" 2>/dev/null | awk 'NR==2{print $2}')}
fs=${fs:-unknown}
rustc=$(rustc --version | awk '{print $2}')

field() { awk -F'\t' -v n="$1" -v c="$2" '$1==n{print $c}' "$TSV"; }
row() { # name label
  printf "| %s | %ss | %ss | %ss | %s MB |\n" "$2" "$(field "$1" 3)" "$(field "$1" 4)" "$(field "$1" 5)" "$(field "$1" 7)"
}
pct() { # 100 * (1 - a/b), rounded
  awk -v a="$1" -v b="$2" 'BEGIN{ if (b > 0) printf "%.0f", 100 * (1 - a / b); else print "?" }'
}

{
  echo "# Benchmark results"
  echo
  echo "Generated by \`bench/ci.sh\`; don't edit by hand. History: [history.tsv](history.tsv)."
  echo
  echo "- Date: $date, cargo-slot \`$rev\`, rustc $rustc"
  echo "- Machine: $cpu, $cores cores, $os, filesystem: $fs"
  echo "- Workload: ripgrep \`${RG_REV:0:12}\`, $N worktrees at different commits, $ROUNDS edit rounds editing \`$EDIT\`, debug builds"
  echo
  echo "CPU is user+sys including rustc, summed over all worktrees. Physical disk"
  echo "is the change in used space on the volume (counts shared blocks once)."
  echo
  echo "| | first builds | edit round 1 | later rounds (each) | disk (physical) |"
  echo "|---|---|---|---|---|"
  row plain "plain \`cargo build\`"
  row slot-1 "\`cargo slot\`, \`CARGO_SLOT_MAX=1\`"
  row slot-n "\`cargo slot\`, \`CARGO_SLOT_MAX=$N\`"
  echo
  echo "With one slot per worktree vs plain cargo:"
  echo "first-build CPU $(pct "$(field slot-n 3)" "$(field plain 3)")% lower,"
  echo "later edit rounds $(awk -v a="$(field slot-n 5)" -v b="$(field plain 5)" 'BEGIN{ if (b > 0) printf "%+.0f", 100 * (a / b - 1); else print "?" }')% CPU,"
  echo "physical disk $(pct "$(field slot-n 7)" "$(field plain 7)")% lower."
} >"$HERE/RESULTS.md"

HIST=$HERE/history.tsv
if [ ! -f "$HIST" ]; then
  printf "date\trev\tos\tfs\tcores\tstrategy\tfirst_wall\tfirst_cpu\tround1_cpu\tlater_cpu\tdisk_mb\tphys_mb\n" >"$HIST"
fi
while IFS=$'\t' read -r name rest; do
  printf "%s\t%s\t%s\t%s\t%s\t%s\t%s\n" "$date" "$rev" "$os" "$fs" "$cores" "$name" "$rest" >>"$HIST"
done <"$TSV"
rm -f "$TSV"

cat "$HERE/RESULTS.md"
